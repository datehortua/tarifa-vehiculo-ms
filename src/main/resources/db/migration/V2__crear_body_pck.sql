CREATE OR REPLACE PACKAGE BODY PCK_SEGUROS_VEHICULO AS
  PROCEDURE SP_GET_TARIFA_VEHICULO
  (
    PNU_VALCOM_VEH IN NUMBER,
    PNU_ANTG_VEH IN NUMBER,
    PNU_EDACLI IN NUMBER,
    PNU_CANSINI IN NUMBER,
    PNU_TARIFA OUT NUMBER,
    PNU_SALERR OUT NUMBER,
    PVA_SALERR OUT VARCHAR2
  ) IS
      LNU_CODERR NUMBER(1) := NULL ;
      LVA_CODERR VARCHAR2(50) := NULL ;

      LNU_PORREC_PRIMBAS CONSTANT NUMBER(5,2) := 3.00;
      LNU_PORREC_ANTVEH CONSTANT NUMBER(5,2) := 15.00;
      LNU_PORREC_EDAMIN_CLI CONSTANT NUMBER(5,2) := 20.00;
      LNU_PORREC_MAXSIN CONSTANT NUMBER(5,2) := 10.00;

      LNU_VALMINCOM_VEH NUMBER(12) := 20000000;
      LNU_MAXANT_VEH_SINREC NUMBER(2)  := 5;
      LNU_MAXEDA_CLI_CONREC NUMBER(2)  := 25;
      LNU_MAXCAN_SINI_SINREC NUMBER(2)  := 1;
      LBO_VALRET BOOLEAN := FALSE;

      LNU_PRIMA_BASE NUMBER(12,2) := 0;
      LNU_REC_ANTVEH NUMBER(12,2) := 0;
      LNU_REC_EDAMIN_CLI NUMBER(12,2) := 0;
      LNU_REC_MAXSIN NUMBER(12,2) := 0;
  BEGIN
       IF (FN_REGNEG_SEGVEH(PNU_VALCOM_VEH, PNU_ANTG_VEH, PNU_EDACLI, PNU_CANSINI, LNU_CODERR, LVA_CODERR)) THEN

            LNU_PRIMA_BASE := (PNU_VALCOM_VEH * (LNU_PORREC_PRIMBAS/100));
            IF (PNU_ANTG_VEH > LNU_MAXANT_VEH_SINREC) THEN
                LNU_REC_ANTVEH := (PNU_VALCOM_VEH * (LNU_PORREC_ANTVEH/100));
            END IF;

            IF (PNU_EDACLI < LNU_MAXEDA_CLI_CONREC) THEN
                LNU_REC_EDAMIN_CLI := (PNU_VALCOM_VEH * (LNU_PORREC_EDAMIN_CLI/100));
            END IF;

            IF (PNU_CANSINI >= LNU_MAXCAN_SINI_SINREC) THEN
                LNU_REC_MAXSIN := (PNU_VALCOM_VEH * (LNU_PORREC_MAXSIN/100));
            END IF;

            PNU_TARIFA := LNU_PRIMA_BASE + LNU_REC_ANTVEH + LNU_REC_EDAMIN_CLI + LNU_REC_MAXSIN;

        ELSE
           PNU_SALERR := LNU_CODERR;
           PVA_SALERR := LVA_CODERR;
        END IF;
  EXCEPTION
      WHEN OTHERS THEN
           PNU_SALERR := 99;
           PVA_SALERR := 'Error de inconsistencia en cálculos de prima';
  END SP_GET_TARIFA_VEHICULO;

  FUNCTION FN_REGNEG_SEGVEH (
      PNU_VALCOM_VEH IN NUMBER,
      PNU_ANTG_VEH   IN NUMBER,
      PNU_EDACLI     IN NUMBER,
      PNU_CANSINI    IN NUMBER,
      PNU_VALERR     IN OUT NUMBER,
      PVA_VALRET     IN OUT VARCHAR2
  ) RETURN BOOLEAN
  IS
      LNU_VALMINCOM_VEH       NUMBER(12) := 20000000;
      LNU_MAXANT_VEH_SINREC   NUMBER(2)  := 1;
      LNU_MAXEDA_CLI_CONREC   NUMBER(2)  := 18;
      LNU_MAXCAN_SINI_SINREC  NUMBER(2)  := 99;
      LBO_VALRET              BOOLEAN := FALSE;

      LNU_CODERR1 CONSTANT NUMBER(1) := 1 ;
      LVA_CODERR1 CONSTANT VARCHAR2(50) := 'Error Valor comercial no válido' ;
      LNU_CODERR2 CONSTANT NUMBER(1) := 2 ;
      LVA_CODERR2 CONSTANT VARCHAR2(50) := 'Error Antiguedad no válida' ;
      LNU_CODERR3 CONSTANT NUMBER(1) := 3 ;
      LVA_CODERR3 CONSTANT VARCHAR2(50) := 'Error Edad cliente no válida' ;
      LNU_CODERR4 CONSTANT NUMBER(1) := 4 ;
      LVA_CODERR4 CONSTANT VARCHAR2(50) := 'Error Cantidad de siniestros no válida' ;
  BEGIN
      IF (PNU_VALCOM_VEH < LNU_VALMINCOM_VEH) THEN
          LBO_VALRET := FALSE;
          PNU_VALERR := LNU_CODERR1;
          PVA_VALRET := LVA_CODERR1;
      ELSIF (PNU_ANTG_VEH < LNU_MAXANT_VEH_SINREC) THEN
          LBO_VALRET := FALSE;
          PNU_VALERR := LNU_CODERR2;
          PVA_VALRET := LVA_CODERR2;
      ELSIF (PNU_EDACLI < LNU_MAXEDA_CLI_CONREC) THEN
          LBO_VALRET := FALSE;
          PNU_VALERR := LNU_CODERR3;
          PVA_VALRET := LVA_CODERR3;
      ELSIF (PNU_CANSINI >= LNU_MAXCAN_SINI_SINREC) THEN
          LBO_VALRET := FALSE;
          PNU_VALERR := LNU_CODERR4;
          PVA_VALRET := LVA_CODERR4;
      ELSE
          LBO_VALRET := TRUE;
          PNU_VALERR := 0;
          PVA_VALRET := NULL;
      END IF;

      RETURN LBO_VALRET;
  END FN_REGNEG_SEGVEH;
END PCK_SEGUROS_VEHICULO;